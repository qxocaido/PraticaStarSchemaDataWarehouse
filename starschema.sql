-- Consulta teste
SELECT
    v.venda_id,
    p.nome AS produto,
    c.nome AS cliente,
    t.data,
    v.quantidade,
    v.valor_total
FROM fato_vendas v
INNER JOIN dim_produto p
    ON v.produto_id = p.produto_id
INNER JOIN dim_cliente c
    ON v.cliente_id = c.cliente_id
INNER JOIN dim_tempo t
    ON v.tempo_id = t.tempo_id;

-- Consulta 1
SELECT
    t.ano,
    t.mes,
    SUM(v.valor_total) AS faturamento
FROM fato_vendas v
JOIN dim_tempo t ON v.tempo_id = t.tempo_id
GROUP BY t.ano, t.mes
ORDER BY t.ano, t.mes;
-- Consulta 2
SELECT
    p.categoria,
    SUM(v.valor_total) AS faturamento
FROM fato_vendas v
JOIN dim_produto p ON v.produto_id = p.produto_id
GROUP BY p.categoria
ORDER BY faturamento DESC;
-- Consulta 3
SELECT
    c.estado,
    SUM(v.valor_total) AS faturamento
FROM fato_vendas v
JOIN dim_cliente c ON v.cliente_id = c.cliente_id
GROUP BY c.estado
ORDER BY faturamento DESC;
-- Consulta 4
SELECT
    p.nome,
    SUM(v.quantidade) AS unidades_vendidas,
    SUM(v.valor_total) AS faturamento
FROM fato_vendas v
JOIN dim_produto p ON v.produto_id = p.produto_id
GROUP BY p.nome
ORDER BY unidades_vendidas DESC;





