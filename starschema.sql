
-- DIMENSÃO PRODUTO
CREATE TABLE dim_produto (
    produto_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    categoria VARCHAR(50),
    marca VARCHAR(50)
);

-- DIMENSÃO CLIENTE
CREATE TABLE dim_cliente (
    cliente_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cidade VARCHAR(100),
    estado CHAR(2)
);

-- DIMENSÃO TEMPO
CREATE TABLE dim_tempo (
    tempo_id INTEGER PRIMARY KEY,
    data DATE NOT NULL UNIQUE,
    dia INTEGER NOT NULL,
    mes INTEGER NOT NULL,
    trimestre INTEGER NOT NULL,
    ano INTEGER NOT NULL
);

-- TABELA FATO
CREATE TABLE fato_vendas (
    venda_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    produto_id INTEGER NOT NULL,
    cliente_id INTEGER NOT NULL,
    tempo_id INTEGER NOT NULL,

    quantidade INTEGER NOT NULL,
    valor_unitario NUMERIC(10,2) NOT NULL,
    valor_total NUMERIC(12,2) NOT NULL,

    FOREIGN KEY (produto_id)
        REFERENCES dim_produto(produto_id),

    FOREIGN KEY (cliente_id)
        REFERENCES dim_cliente(cliente_id),

    FOREIGN KEY (tempo_id)
        REFERENCES dim_tempo(tempo_id)
);


